import { sqlite } from '../db/client.js'
import { openPlatformDb } from './platform-metrics.js'

/**
 * Cross-Platform Alert Generation
 *
 * Each platform already computes its own real alerts/recommendations inside its own live
 * DB (Meesho's Supplier Panel rules, Snapdeal's Health Gate rules, Flipkart's recommend engine).
 * This mirrors those OPEN rows into amazon/server's shared `alerts` table (read directly from
 * each platform's own SQLite file - readOnly, no HTTP), so the cross-platform /v1/alerts(/stats)
 * endpoints show the same real counts the platform's own app shows - not raw_ingest rows no one
 * writes anymore.
 */

/** amazon/server's alerts table + /v1/alerts(/stats) expect severity 'red' | 'amber' | anything-else(=green). */
function toRedAmberGreen(native: string | null | undefined): 'red' | 'amber' | 'green' {
  const s = (native || '').toLowerCase()
  if (s === 'critical' || s === 'high') return 'red'
  if (s === 'warning' || s === 'medium') return 'amber'
  return 'green'
}

export function generateMeeshoAlerts() {
  const alerts: any[] = []
  const db = openPlatformDb('meesho')
  if (!db) return alerts
  try {
    const rows = db
      .prepare(
        `SELECT id, ts, severity, listing_id, code, message FROM alerts
         WHERE acknowledged = 0 ORDER BY id DESC LIMIT 50`
      )
      .all() as Array<{ id: number; ts: string; severity: string; listing_id: number | null; code: string | null; message: string | null }>
    for (const r of rows) {
      alerts.push({
        rule_id: `meesho_sync_${r.code || 'alert'}_${r.id}`,
        severity: toRedAmberGreen(r.severity),
        title: `Meesho: ${r.code || 'Issue'}${r.listing_id ? ` (listing #${r.listing_id})` : ''}`,
        message: r.message || '',
        action: 'Open the Meesho Alerts page for details.',
        marketplace: 'meesho',
      })
    }
  } catch (err) {
    console.error('[platform-alerts] Meesho read failed:', err)
  } finally {
    db.close()
  }
  return alerts
}

export function generateSnapdealAlerts() {
  const alerts: any[] = []
  const db = openPlatformDb('snapdeal')
  if (!db) return alerts
  try {
    const rows = db
      .prepare(
        `SELECT id, ts, severity, code, title, reason FROM alerts
         WHERE status = 'open' ORDER BY id DESC LIMIT 50`
      )
      .all() as Array<{ id: number; ts: string; severity: string; code: string | null; title: string | null; reason: string | null }>
    for (const r of rows) {
      alerts.push({
        rule_id: `snapdeal_sync_${r.code || r.id}_${r.id}`,
        severity: toRedAmberGreen(r.severity),
        title: `Snapdeal: ${r.title || r.code || 'Issue'}`,
        message: r.reason || '',
        action: 'Open the Snapdeal Alerts page for details.',
        marketplace: 'snapdeal',
      })
    }
  } catch (err) {
    console.error('[platform-alerts] Snapdeal read failed:', err)
  } finally {
    db.close()
  }
  return alerts
}

